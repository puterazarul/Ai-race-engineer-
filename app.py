import sys
from pathlib import Path

import plotly.graph_objects as go
import streamlit as st

sys.path.insert(0, str(Path(__file__).parent))
from src.analysis import compare_laps, format_time, lap_stats, load_telemetry, summary
from src.generate_sample_data import generate

CSV = Path(__file__).parent / "data" / "sample" / "telemetry.csv"

st.set_page_config(page_title="AI Race Engineer", page_icon="🏁", layout="wide")


@st.cache_data
def get_data():
    if not CSV.exists():
        generate(path=CSV)
    return load_telemetry(CSV)


def line_chart(df, laps, col, title, unit):
    fig = go.Figure()
    for lap in laps:
        d = df[df["lap"] == lap]
        fig.add_trace(go.Scatter(x=d["distance_m"], y=d[col], name=f"Lap {lap}", mode="lines"))
    fig.update_layout(title=title, xaxis_title="Distance (m)", yaxis_title=unit,
                      height=320, margin=dict(l=10, r=10, t=40, b=10), hovermode="x unified")
    return fig


df = get_data()
stats = lap_stats(df)
s = summary(stats)
laps = stats["lap"].tolist()

st.title("🏁 AI Race Engineer")
st.caption("Telemetry analysis dashboard. Data is SIMULATED, and insights are rule-based, not generative AI.")

c1, c2, c3, c4 = st.columns(4)
c1.metric("Total laps", s["total_laps"])
c2.metric("Fastest lap", format_time(s["fastest_time"]), f"Lap {s['fastest_lap']}", delta_color="off")
c3.metric("Average lap time", format_time(s["avg_lap_time"]))
c4.metric("Max speed", f"{s['max_speed']:.1f} km/h")

st.subheader("Lap times")
view = stats.copy()
view["lap_time"] = view["lap_time_s"].map(format_time)
st.dataframe(view[["lap", "lap_time", "avg_speed_kmh", "max_speed_kmh", "min_speed_kmh"]].round(1),
             hide_index=True, width="stretch")

st.subheader("Lap comparison")
col_a, col_b = st.columns(2)
lap_a = col_a.selectbox("Lap A", laps, index=0)
lap_b = col_b.selectbox("Lap B", laps, index=min(1, len(laps) - 1))

if lap_a == lap_b:
    st.info("Pick two different laps to compare.")
else:
    t = stats.set_index("lap")["lap_time_s"]
    ta, tb = t[lap_a], t[lap_b]
    winner = lap_a if ta < tb else lap_b
    m1, m2, m3 = st.columns(3)
    m1.metric(f"Lap {lap_a}", format_time(ta))
    m2.metric(f"Lap {lap_b}", format_time(tb))
    m3.metric("Faster lap", f"Lap {winner}", f"-{abs(ta - tb):.3f} s")

    st.plotly_chart(line_chart(df, [lap_a, lap_b], "speed_kmh", "Speed vs distance", "km/h"),
                    width="stretch")
    g1, g2 = st.columns(2)
    g1.plotly_chart(line_chart(df, [lap_a, lap_b], "throttle_pct", "Throttle vs distance", "%"),
                    width="stretch")
    g2.plotly_chart(line_chart(df, [lap_a, lap_b], "brake_pct", "Brake vs distance", "%"),
                    width="stretch")

    st.subheader("🎙️ Race Engineer Insights")
    for note in compare_laps(df, lap_a, lap_b):
        st.write(("💡 " if note.startswith("Recommendation") else "• ") + note)

with st.expander("About this data"):
    st.write("Telemetry is generated by `src/generate_sample_data.py`. It is simulated, "
             "not recorded from Assetto Corsa or any real car. Insights come from Python "
             "rules applied to calculated values.")
